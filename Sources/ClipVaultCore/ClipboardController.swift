import AppKit
import Combine
import CryptoKit

@MainActor public final class ClipboardController: ObservableObject {
    public static let sensitiveRevealSeconds: TimeInterval = 10
    private struct OpenVault {
        let id: UUID
        var document: VaultDocument
        let key: SymmetricKey
        var deadline: TimeInterval
    }
    private enum Session { case locked, unlocking(UUID), unlocked(OpenVault) }
    @Published private var session: Session = .locked
    @Published public private(set) var message: String?
    @Published public private(set) var revision = UUID()
    @Published public private(set) var captureFailed = false
    private let storage: VaultStorage
    private let keys: VaultKeyProvider
    private let inbox: EncryptedCaptureInbox
    private var captureConfiguration: CaptureConfiguration?
    private let pasteboard: NSPasteboard
    private let uptime: () -> TimeInterval
    private let now: () -> Date
    private var changeCount: Int
    private var copiedChangeCount: Int?
    private var copiedDeadline: TimeInterval?
    private var timer: Timer?
    private var revealDeadlines: [UUID: TimeInterval] = [:]
    private static let ownType = NSPasteboard.PasteboardType("local.clipvault.clip")
    private static let ignoredTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"].map { NSPasteboard.PasteboardType($0) }

    public init(storage: VaultStorage, keys: VaultKeyProvider, inbox: EncryptedCaptureInbox, pasteboard: NSPasteboard,
                uptime: @escaping () -> TimeInterval = { ProcessInfo.processInfo.systemUptime },
                now: @escaping () -> Date = Date.init) {
        self.storage = storage
        self.keys = keys
        self.inbox = inbox
        self.pasteboard = pasteboard
        self.uptime = uptime
        self.now = now
        changeCount = pasteboard.changeCount
        do { captureConfiguration = try storage.captureConfiguration() }
        catch { captureFailed = true; message = "Encrypted background capture is unavailable. Unlock the vault to check its storage. " + error.localizedDescription }
    }

    public var isUnlocked: Bool {
        if case .unlocked(let vault) = session { return uptime() < vault.deadline }
        return false
    }
    public var isUnlocking: Bool { if case .unlocking = session { return true }; return false }
    public var isNew: Bool { !storage.exists }
    public var entries: [ClipboardEntry] { guard isUnlocked, case .unlocked(let vault) = session else { return [] }; return vault.document.entries }
    public var settings: VaultSettings { guard isUnlocked, case .unlocked(let vault) = session else { return VaultSettings() }; return vault.document.settings }
    public var isCapturing: Bool { captureConfiguration?.policy.enabled == true && !captureFailed }
    public var needsCaptureMigration: Bool { storage.exists && captureConfiguration == nil }
    public var secondsRemaining: Int {
        guard case .unlocked(let vault) = session else { return 0 }
        return max(0, Int(ceil(vault.deadline - uptime())))
    }

    public func startTimer() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.tick() }
        }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }

    public func unlock() async {
        guard !isUnlocked && !isUnlocking else { return }
        let attempt = UUID()
        session = .unlocking(attempt)
        message = nil
        do {
            let existed = storage.exists
            let key = try await keys.unlock(allowCreation: !existed)
            guard case .unlocking(let current) = session, current == attempt else { return }
            var document = existed ? try storage.load(key: key) : VaultDocument()
            if document.capturePrivateKey == nil { document.capturePrivateKey = P256.KeyAgreement.PrivateKey().rawRepresentation }
            try importPending(into: &document)
            try document.prune(now: now())
            try storage.save(document, key: key)
            captureConfiguration = try CaptureConfiguration(document: document)
            captureFailed = false
            revision = UUID()
            session = .unlocked(OpenVault(id: attempt, document: document, key: key, deadline: uptime() + document.settings.autoLockSeconds))
            do { try inbox.acknowledge(through: document.lastImportedSequence ?? 0) }
            catch { captureFailed = true; message = "History was imported, but encrypted inbox cleanup failed. " + error.localizedDescription }
        } catch {
            guard case .unlocking(let current) = session, current == attempt else { return }
            session = .locked
            keys.cancel()
            message = error.localizedDescription
        }
    }

    public func lock() {
        keys.cancel()
        hideSensitivePreviews()
        session = .locked
        revision = UUID()
        if !captureFailed { message = nil }
        clearOwnedClipboard()
    }

    @discardableResult public func interact() -> Bool {
        guard var vault = authorized() else { return false }
        vault.deadline = uptime() + vault.document.settings.autoLockSeconds
        session = .unlocked(vault)
        return true
    }

    public func dismissMessage() { message = nil }

    public func isValueVisible(_ entry: ClipboardEntry) -> Bool {
        isUnlocked && (!entry.isSensitive || (revealDeadlines[entry.id] ?? 0) > uptime())
    }

    public func revealSecondsRemaining(_ entry: ClipboardEntry) -> Int {
        guard isUnlocked, entry.isSensitive, let deadline = revealDeadlines[entry.id] else { return 0 }
        return max(0, Int(ceil(deadline - uptime())))
    }

    public func matches(_ entry: ClipboardEntry, search: String) -> Bool {
        guard isUnlocked else { return false }
        return search.isEmpty || entry.name?.localizedCaseInsensitiveContains(search) == true ||
            (isValueVisible(entry) && entry.text.localizedCaseInsensitiveContains(search))
    }

    public func setSensitive(_ id: UUID, isSensitive: Bool) {
        guard interact(), let vault = authorized(), let entry = vault.document.entries.first(where: { $0.id == id }) else { return }
        do {
            var document = vault.document
            let matching = document.entries.indices.filter { document.entries[$0].text == entry.text }
            for index in matching { document.entries[index].isSensitive = isSensitive }
            try commit(document, from: vault)
            for index in matching { revealDeadlines.removeValue(forKey: document.entries[index].id) }
        } catch { message = error.localizedDescription }
    }

    public func rename(_ id: UUID, name: String) {
        mutateEntry(id) { $0.name = try ClipboardEntry.normalizedName(name) }
    }

    public func revealValue(_ id: UUID) {
        guard interact(), let vault = authorized(), vault.document.entries.contains(where: { $0.id == id && $0.isSensitive }) else { return }
        objectWillChange.send()
        revealDeadlines[id] = uptime() + Self.sensitiveRevealSeconds
    }

    public func hideValue(_ id: UUID) {
        _ = interact()
        objectWillChange.send()
        revealDeadlines.removeValue(forKey: id)
    }

    public func hideSensitivePreviews() {
        objectWillChange.send()
        revealDeadlines.removeAll()
    }

    public func saveSettings(_ settings: VaultSettings) {
        guard interact(), let vault = authorized() else { return }
        do {
            var document = vault.document
            document.settings = try settings.validated()
            try document.prune(now: now())
            try commit(document, from: vault, deadline: uptime() + settings.autoLockSeconds)
            changeCount = pasteboard.changeCount
            captureFailed = false
        } catch { message = error.localizedDescription }
    }

    public func toggleCapture() {
        var settings = self.settings
        settings.captureEnabled = !settings.captureEnabled || captureFailed
        saveSettings(settings)
    }

    public func softDelete(_ id: UUID) {
        mutateEntry(id) { $0.deletedAt = self.now() }
    }

    public func restore(_ id: UUID) { mutateEntry(id) { $0.deletedAt = nil } }

    public func permanentlyDelete(_ id: UUID) {
        guard interact(), let vault = authorized(), let entry = vault.document.entries.first(where: { $0.id == id }) else { return }
        do {
            var document = vault.document
            document.entries.removeAll { $0.id == id }
            try commit(document, from: vault)
            clearClipboard(matching: entry.text)
        } catch { message = error.localizedDescription }
    }

    public func copy(_ id: UUID) {
        guard interact(), let vault = authorized(), let entry = vault.document.entries.first(where: { $0.id == id && $0.deletedAt == nil }) else { return }
        let item = NSPasteboardItem()
        item.setString(entry.text, forType: .string)
        item.setData(Data(), forType: Self.ownType)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else { message = VaultError.clipboardWriteFailed.localizedDescription; return }
        changeCount = pasteboard.changeCount
        copiedChangeCount = changeCount
        copiedDeadline = uptime() + vault.document.settings.clipboardClearSeconds
    }

    public func tick(frontmostBundleID: String? = NSWorkspace.shared.frontmostApplication?.bundleIdentifier) {
        if let deadline = copiedDeadline, uptime() >= deadline { clearOwnedClipboard() }
        _ = authorized()
        revealDeadlines = revealDeadlines.filter { $0.value > uptime() }
        objectWillChange.send()
        guard isCapturing, let configuration = captureConfiguration else { changeCount = pasteboard.changeCount; return }
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            captureFailed = true
            message = "macOS denied clipboard access. Allow ClipVault in System Settings clipboard privacy controls, then resume listening."
            return
        }
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let policy = configuration.policy
        guard !policy.excludedApps.contains(frontmostBundleID ?? ""),
              pasteboard.availableType(from: [Self.ownType]) == nil,
              !(policy.ignoreConcealed && pasteboard.availableType(from: Self.ignoredTypes) != nil),
              let text = pasteboard.string(forType: .string), !text.isEmpty,
              text.utf8.count <= 1024 * 1024 else { return }
        guard isCapturing, captureConfiguration == configuration else { return }
        do {
            try inbox.enqueue(ClipboardEntry(text: text, createdAt: now()), configuration: configuration, now: now())
            if let vault = authorized() {
                var document = vault.document
                try importPending(into: &document)
                try document.prune(now: now())
                try commit(document, from: vault)
                try inbox.acknowledge(through: document.lastImportedSequence ?? 0)
            }
        } catch {
            if case VaultError.sessionExpired = error { return }
            captureFailed = true
            message = "Capture paused because encrypted storage could not be updated. " + error.localizedDescription
        }
    }

    private func importPending(into document: inout VaultDocument) throws {
        guard let privateKey = document.capturePrivateKey else { throw VaultError.invalidFormat }
        let batch = try inbox.read(after: document.lastImportedSequence ?? 0, privateKey: privateKey)
        var known = Set(document.entries.map(\.id))
        for var entry in batch.entries {
            guard known.insert(entry.id).inserted else { continue }
            let matches = document.entries.filter { $0.text == entry.text }
            entry.isSensitive = entry.isSensitive || matches.contains(where: \.isSensitive)
            entry.name = entry.name ?? matches.first(where: { $0.name != nil })?.name
            if let first = document.entries.firstIndex(where: { $0.deletedAt == nil }), document.entries[first].text == entry.text {
                document.entries[first].isSensitive = document.entries[first].isSensitive || entry.isSensitive
                document.entries[first].name = document.entries[first].name ?? entry.name
            } else { document.entries.insert(entry, at: 0) }
        }
        document.lastImportedSequence = batch.lastSequence
    }

    private func authorized() -> OpenVault? {
        guard case .unlocked(let vault) = session else { return nil }
        guard uptime() < vault.deadline else { lock(); return nil }
        return vault
    }

    private func commit(_ document: VaultDocument, from vault: OpenVault, deadline: TimeInterval? = nil) throws {
        guard let current = authorized(), current.id == vault.id else { throw VaultError.sessionExpired }
        try storage.save(document, key: vault.key)
        captureConfiguration = try CaptureConfiguration(document: document)
        guard let current = authorized(), current.id == vault.id else { throw VaultError.sessionExpired }
        session = .unlocked(OpenVault(id: vault.id, document: document, key: vault.key, deadline: deadline ?? vault.deadline))
    }

    @discardableResult private func mutateEntry(_ id: UUID, mutation: (inout ClipboardEntry) throws -> Void) -> Bool {
        guard interact(), let vault = authorized(), let index = vault.document.entries.firstIndex(where: { $0.id == id }) else { return false }
        do {
            var document = vault.document
            let wasDeleted = document.entries[index].deletedAt != nil
            try mutation(&document.entries[index])
            try document.entries[index].validate()
            try commit(document, from: vault)
            if !wasDeleted && document.entries[index].deletedAt != nil { clearClipboard(matching: document.entries[index].text) }
            return true
        } catch { message = error.localizedDescription; return false }
    }

    private func clearClipboard(matching text: String) {
        if pasteboard.string(forType: .string) == text { pasteboard.clearContents(); changeCount = pasteboard.changeCount }
    }

    private func clearOwnedClipboard() {
        if let count = copiedChangeCount, pasteboard.changeCount == count,
           pasteboard.availableType(from: [Self.ownType]) != nil {
            pasteboard.clearContents()
            changeCount = pasteboard.changeCount
        }
        copiedChangeCount = nil
        copiedDeadline = nil
    }
}
